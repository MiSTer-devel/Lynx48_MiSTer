#!/usr/bin/env python3
# Writes rtl/lynx_font.vh: the Lynx's own text font, read from the 48K ROM (roms/src/lynx48-1.ic46,
# offset 01D4h: characters 20h-7Fh, 10 rows each, 5 pixels in bits 4-0, bit 4 = left).
# Used by rtl/lynx_tape_overlay.sv for the tape status bar and the next-step hint.
#   python3 tools/make_font.py
import os
here = os.path.dirname(os.path.abspath(__file__))
rom = open(os.path.join(here, '..', 'roms', 'src', 'lynx48-1.ic46'), 'rb').read()
font = rom[0x1D4:0x1D4 + 96 * 10]
out = ['// Generated by tools/make_font.py from the Lynx 48K ROM (lynx48-1.ic46 at 01D4h): do not edit.',
       '// lynx_font(code, row): row 0-9 of character code 20h-7Fh, 5 pixels in bits 4-0 (bit 4 = left).',
       'function automatic [4:0] lynx_font(input [6:0] code, input [3:0] row);',
       '\tcase ({code, row})']
for c in range(96):
    for r in range(10):
        b = font[c * 10 + r] & 0x1F
        if b:
            out.append("\t\t11'h%03X: lynx_font = 5'h%02X;" % (((c + 0x20) << 4) | r, b))
out += ['\t\tdefault: lynx_font = 5\'h00;', '\tendcase', 'endfunction', '']
open(os.path.join(here, '..', 'rtl', 'lynx_font.vh'), 'w').write('\n'.join(out))
print('rtl/lynx_font.vh: %d rows' % (len(out) - 7))
